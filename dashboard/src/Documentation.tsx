import { useRef, useState } from "react";
import type { LiveRun } from "./liveRun";
import "./Documentation.css";

export default function Documentation({
  live,
  onNavigate,
  onInspect,
}: {
  live: LiveRun;
  onNavigate: (view: string) => void;
  onInspect: (ruleKey: string) => void;
}) {
  const doc = live.doc;
  const [section, setSection] = useState("Business rules");
  const reader = useRef<HTMLDivElement>(null);
  const overview = useRef<HTMLHeadingElement>(null);
  const businessRules = useRef<HTMLHeadingElement>(null);
  const isMain = section === "Business rules" || section === "System overview";
  const extra = doc.sections.find((item) => item.title === section);
  const selectSection = (next: string) => {
    setSection(next);
    requestAnimationFrame(() => {
      const heading =
        next === "Business rules" ? businessRules.current : overview.current;
      if (reader.current)
        reader.current.scrollTop =
          next === "Business rules" || next === "System overview"
            ? (heading?.offsetTop ?? 0)
            : 0;
    });
  };
  return (
    <>
      <div className="ws-tabs doc-tabs" role="tablist" aria-label="Run views">
        {["Overview", "Code & rules", "Validation", "Documentation"].map(
          (name) => (
            <button
              key={name}
              id={`doc-tab-${name.replaceAll(" ", "-")}`}
              role="tab"
              aria-selected={name === "Documentation"}
              aria-controls={
                name === "Documentation" ? "documentation-panel" : undefined
              }
              onClick={() => onNavigate(name)}
            >
              {name}
            </button>
          ),
        )}
      </div>
      <div
        className="doc-layout"
        id="documentation-panel"
        role="tabpanel"
        aria-labelledby="doc-tab-Documentation"
      >
        <nav
          className="doc-contents ws-panel"
          aria-label="Documentation contents"
        >
          <h2>CONTENTS</h2>
          {[
            "System overview",
            "Business rules",
            ...doc.sections.map((item) => item.title),
          ].map((name) => (
            <button
              key={name}
              className={section === name ? "selected" : ""}
              aria-current={section === name ? "location" : undefined}
              onClick={() => selectSection(name)}
            >
              {name}
            </button>
          ))}
        </nav>
        <article
          className="doc-reader ws-panel"
          aria-label="Generated system documentation"
        >
          <img
            className="ws-trim"
            src="/design/documentation/3e0dc.svg"
            alt=""
          />
          <div className="doc-reader-scroll" ref={reader}>
            <h2 className="doc-title">{doc.title}</h2>
            <p className="doc-attribution">
              Generated by {doc.generatedBy} · Source zip {doc.sourceRevision}
            </p>
            {isMain ? (
              <>
                <h3 className="doc-section-title" ref={overview}>
                  System overview
                </h3>
                <p className="doc-overview">{doc.overview}</p>
                <hr />
                <h3 className="doc-section-title" ref={businessRules}>
                  Extracted business rules ({doc.rules.length})
                </h3>
                <div className="doc-rule-list">
                  {doc.rules.map((rule) => (
                    <button
                      key={rule.key}
                      className="doc-rule"
                      onClick={() => onInspect(rule.key)}
                      aria-label={`Inspect ${rule.id}: ${rule.title}`}
                    >
                      <strong>
                        {rule.id} · {rule.title}
                      </strong>
                      <span>{rule.description}</span>
                    </button>
                  ))}
                  {!doc.rules.length && <p>No business rules extracted yet.</p>}
                </div>
                <h3 className="doc-review-title">Review notes</h3>
                <p className="doc-review-notes">{doc.reviewNotes}</p>
              </>
            ) : (
              extra && (
                <section
                  className="doc-extra"
                  aria-labelledby="doc-extra-title"
                >
                  <h3 className="doc-section-title" id="doc-extra-title">
                    {extra.title}
                  </h3>
                  {extra.paragraphs.map((paragraph, i) => (
                    <p key={i}>{paragraph}</p>
                  ))}
                  {section === "Verification" && (
                    <button
                      className="doc-text-link"
                      onClick={() => onNavigate("Validation")}
                    >
                      Inspect validation evidence →
                    </button>
                  )}
                  <h3 className="doc-review-title">Review notes</h3>
                  <p>{doc.reviewNotes}</p>
                </section>
              )
            )}
          </div>
        </article>
      </div>
    </>
  );
}
