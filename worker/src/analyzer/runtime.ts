// Legacy runtime: Dockerfile generation (when the zip has none) and the
// compile probe, which syntax-checks every program inside the locked-down
// container. The probe is the evidence for "this program can run in Docker".

import { runLocked } from '../docker.ts';
import { profile, PROFILES } from './languages.ts';
import type { CompileResult, Component, InventoryFile } from './scan.ts';

/** Where the project is copied inside the legacy image. */
export const LEGACY_DIR = '/legacy';
const BASE_IMAGE = 'debian:bookworm-slim';

/** Single-quotes a string for sh. */
export const shq = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`;

/**
 * Builds a Dockerfile for a project without one: the toolchains of every
 * detected language, plus the project copied to /legacy. Nothing runs at
 * build time except the package install; programs are compiled later,
 * inside locked-down containers.
 */
export function generateDockerfile(languageIds: string[]): { dockerfile: string; runtime: string } {
  const runtimes = languageIds.map(id => profile(id)?.runtime).filter(r => r !== undefined);
  const lines = [
    '# Generated by AgentProof: the legacy zip had no Dockerfile.',
    `FROM ${BASE_IMAGE}`,
    'ENV DEBIAN_FRONTEND=noninteractive',
    ...[...new Set(runtimes.flatMap(r => r.install))],
    `WORKDIR ${LEGACY_DIR}`,
    `COPY . ${LEGACY_DIR}`,
    '',
  ];
  const runtime = runtimes.length ? runtimes.map(r => r.name).join(' + ') : `${BASE_IMAGE} (no toolchain for the detected languages)`;
  return { dockerfile: lines.join('\n'), runtime };
}

/** Languages to install, by source lines (only ones we have a runtime for). */
export function detectLanguages(inventory: InventoryFile[]): string[] {
  const lines = new Map<string, number>();
  for (const f of inventory) {
    if (f.kind === 'source' && f.language) lines.set(f.language, (lines.get(f.language) ?? 0) + f.lines);
  }
  return [...lines].sort((a, b) => b[1] - a[1]).map(([id]) => id).filter(id => PROFILES.some(p => p.id === id && p.runtime));
}

/**
 * Syntax-checks every component in one locked-down container (no network,
 * read-only, no env vars). Tries each of the profile's commands in order.
 * The extracted project (`extractDir`) is mounted read-only at /legacy, so
 * this works the same for generated and provided Dockerfiles; the image only
 * has to supply the toolchain. `root` is ScanResult.root.
 */
export async function probeCompile(
  image: string,
  extractDir: string,
  components: Component[],
  inventory: InventoryFile[],
  root: string,
  opts: { timeoutMs?: number } = {}
): Promise<Map<string, CompileResult>> {
  const results = new Map<string, CompileResult>();
  const abs = (rel: string) => `${LEGACY_DIR}/${root}${rel}`;
  const script: string[] = [
    // check <file> <cmd>...: prints OK/FAIL/NOTOOL with the winning command,
    // or the FIRST real error (later variants are fallbacks, e.g. free format,
    // and their errors are usually less meaningful).
    'check() {',
    '  f="$1"; shift; real=""; tool=""',
    '  for c in "$@"; do',
    '    out=$(eval "$c" 2>&1); rc=$?',
    '    if [ $rc -eq 0 ]; then printf "OK\\t%s\\t%s\\n" "$f" "$c"; return; fi',
    '    if [ $rc -eq 127 ]; then tool="$out"; elif [ -z "$real" ]; then real="$out"; fi',
    '  done',
    '  if [ -n "$real" ]; then',
    '    err=$(printf "%s\\n" "$real" | grep -i -m1 "error" || printf "%s\\n" "$real" | head -n1)',
    '    printf "FAIL\\t%s\\t%s\\n" "$f" "$err"',
    '  else',
    '    printf "NOTOOL\\t%s\\t%s\\n" "$f" "$(printf "%s\\n" "$tool" | head -n1)"',
    '  fi',
    '}',
  ];

  for (const c of components) {
    const p = profile(c.language);
    if (!p?.runtime) {
      results.set(c.path, { status: 'unavailable', error: `no ${c.language} toolchain profile` });
      continue;
    }
    const includeDirs = [...new Set(inventory.filter(f => f.kind === 'include' && f.language === c.language).map(f => f.path.split('/').slice(0, -1).join('/')))];
    const includes = includeDirs.map(d => `${p.runtime!.includeFlag} ${shq(abs(d) || LEGACY_DIR)}`).join(' ');
    const commands = p.runtime.syntaxCheck.map(cmd => cmd.replace('{includes}', includes).replace('{file}', shq(abs(c.path))));
    script.push(`check ${shq(c.path)} ${commands.map(shq).join(' ')}`);
  }

  if (results.size === components.length) return results;
  const r = await runLocked(image, ['sh', '-s'], {
    stdin: script.join('\n') + '\n',
    timeoutMs: opts.timeoutMs ?? 5 * 60_000,
    mounts: [{ host: extractDir, container: LEGACY_DIR }],
  });
  if (r.timedOut) throw new Error('compile probe timed out');

  const prefix = `${LEGACY_DIR}/${root}`;
  for (const line of r.stdout.split('\n')) {
    const [status, file, detail = ''] = line.split('\t');
    if (!file) continue;
    const clean = detail.split(prefix).join('').trim().slice(0, 300);
    if (status === 'OK') results.set(file, { status: 'ok', command: clean });
    else if (status === 'FAIL') results.set(file, { status: 'failed', error: clean });
    else if (status === 'NOTOOL') results.set(file, { status: 'unavailable', error: clean || 'compiler not installed in the image' });
  }
  for (const c of components) {
    if (!results.has(c.path)) results.set(c.path, { status: 'unavailable', error: `probe produced no result (exit ${r.exitCode}) ${r.stderr.slice(0, 200)}` });
  }
  return results;
}
